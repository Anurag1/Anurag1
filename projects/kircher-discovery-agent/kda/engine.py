from __future__ import annotations
from dataclasses import dataclass, asdict
from itertools import combinations
from typing import Iterable
import json

@dataclass(frozen=True)
class Claim:
    id: str
    subject: str
    predicate: str
    object: str
    domain: str
    source: str
    conditions: tuple[str, ...] = ()
    status: str = "unverified"

@dataclass
class Candidate:
    title: str
    connection: str
    rationale: str
    hypothesis: str
    prediction: str
    falsification_test: str
    evidence: list[str]
    status: str = "candidate; not established"

class KircherDiscoveryAgent:
    """Dependency-free symbolic scaffold for evidence-aware discovery candidates."""
    def __init__(self, claims: Iterable[Claim] = ()):
        self.claims: dict[str, Claim] = {c.id: c for c in claims}

    def add_claim(self, claim: Claim) -> None:
        if claim.id in self.claims:
            raise ValueError(f"Duplicate claim id: {claim.id}")
        if not all([claim.subject.strip(), claim.predicate.strip(), claim.object.strip(), claim.source.strip()]):
            raise ValueError("subject, predicate, object, and source are required")
        self.claims[claim.id] = claim

    def graph(self) -> dict:
        nodes = {}
        edges = []
        for c in self.claims.values():
            for entity in (c.subject, c.object):
                nodes.setdefault(entity, {"id": entity, "domains": set()})["domains"].add(c.domain)
            edges.append({"claim_id": c.id, "source": c.subject, "relation": c.predicate, "target": c.object,
                          "domain": c.domain, "evidence_source": c.source, "conditions": list(c.conditions), "status": c.status})
        return {"nodes": [{**v, "domains": sorted(v["domains"])} for v in nodes.values()], "edges": edges}

    def cross_domain_candidates(self, limit: int = 10) -> list[Candidate]:
        if limit < 1:
            raise ValueError("limit must be >= 1")
        claims = list(self.claims.values())
        out = []
        for a, b in combinations(claims, 2):
            if a.domain == b.domain:
                continue
            shared_entities = {a.subject.lower(), a.object.lower()} & {b.subject.lower(), b.object.lower()}
            shared_predicate = a.predicate.lower() == b.predicate.lower()
            if not shared_entities and not shared_predicate:
                continue
            bridge = ", ".join(sorted(shared_entities)) if shared_entities else f"relation '{a.predicate}'"
            out.append(Candidate(
                title=f"Cross-domain candidate: {a.domain} × {b.domain}",
                connection=f"{a.id} ↔ {b.id} via {bridge}",
                rationale=f"A claim in {a.domain} and a claim in {b.domain} share {bridge}. This is a structural analogy to investigate, not proof of a shared law.",
                hypothesis=f"A representation or method used in {a.domain} may help explain or predict a defined task in {b.domain}.",
                prediction=f"On a preregistered task in {b.domain}, a method adapted from {a.domain} will outperform a matched baseline on a specified metric.",
                falsification_test="Predefine task, metric, sample size and baseline; test on held-out data. Reject if the confidence interval excludes the minimum useful effect or results fail to replicate.",
                evidence=[f"{a.id}: {a.subject} —{a.predicate}→ {a.object} [{a.source}; {a.status}]",
                          f"{b.id}: {b.subject} —{b.predicate}→ {b.object} [{b.source}; {b.status}]"],
            ))
            if len(out) >= limit:
                break
        return out

    def contradiction_candidates(self) -> list[dict]:
        results = []
        for a, b in combinations(self.claims.values(), 2):
            if (a.subject.lower(), a.predicate.lower()) != (b.subject.lower(), b.predicate.lower()) or a.object.lower() == b.object.lower():
                continue
            same_conditions = set(a.conditions) == set(b.conditions)
            results.append({"claim_a": a.id, "claim_b": b.id, "claim_a_value": a.object, "claim_b_value": b.object,
                "possible_conflict": same_conditions,
                "reason": "Same subject, relation and recorded conditions; inspect for conflict." if same_conditions else "Different recorded conditions; may not be contradictory.",
                "evidence": [a.source, b.source], "status": "requires adjudication"})
        return results

    def report(self, limit: int = 10) -> dict:
        return {"agent": "Kircher Discovery Agent", "version": "0.1.0", "claim_count": len(self.claims),
                "graph": self.graph(), "cross_domain_candidates": [asdict(x) for x in self.cross_domain_candidates(limit)],
                "possible_contradictions": self.contradiction_candidates(),
                "warning": "Candidates are generated by symbolic heuristics. They are not verified discoveries, proof of novelty, or causal findings."}

    @classmethod
    def from_json(cls, path: str) -> "KircherDiscoveryAgent":
        with open(path, encoding="utf-8") as f:
            raw = json.load(f)
        claims = [Claim(**{**x, "conditions": tuple(x.get("conditions", []))}) for x in raw.get("claims", [])]
        return cls(claims)
